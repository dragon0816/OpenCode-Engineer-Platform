export type WebMessageCode = keyof typeof messages;
type MessageParams = Record<string, string | number>;

export function webMessage(code: WebMessageCode, params?: MessageParams) {
  const text = messages[code].replace(/\{(\w+)\}/g, (match, name: string) =>
    params && Object.hasOwn(params, name) ? String(params[name]) : match);
  return { code, ...(params && { params }), text };
}

const fallbackCodes = new Map(Object.entries(messages).map(([code, text]) => [text, code as WebMessageCode]));

export function codeForFallback(text: string) {
  return fallbackCodes.get(text);
}

