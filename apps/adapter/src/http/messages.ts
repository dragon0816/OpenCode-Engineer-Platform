const repositoryTableIssues: [RegExp, WebMessageCode][] = [
  [/^Unsupported BI schema at (\w+)\.$/, 'repository-bi-table-schema'],
  [/^BI row limit exceeded at (\w+)\.$/, 'repository-bi-table-limit'],
  [/^Invalid BI row at (\w+)\.$/, 'repository-bi-invalid-row'],
  [/^Unknown BI card reference at (\w+)\.$/, 'repository-bi-card-reference'],
];

export function describeRepositoryIssue(text: string) {
  const code = repositoryIssues.get(text);
  if (code) return webMessage(code);
  for (const [pattern, fallback] of repositoryTableIssues) {
    const match = pattern.exec(text);
    if (match) return webMessage(fallback, { table: match[1] });
  }
  return webMessage('repository-import-failed');
}
